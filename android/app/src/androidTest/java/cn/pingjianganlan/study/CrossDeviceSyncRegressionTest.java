package cn.pingjianganlan.study;

import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertTrue;
import static org.junit.Assert.fail;

import android.content.Context;
import android.content.ContextWrapper;

import androidx.test.ext.junit.runners.AndroidJUnit4;
import androidx.test.platform.app.InstrumentationRegistry;

import org.json.JSONArray;
import org.json.JSONException;
import org.json.JSONObject;
import org.junit.Test;
import org.junit.runner.RunWith;

import java.io.ByteArrayOutputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.IOException;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.nio.file.AtomicMoveNotSupportedException;
import java.nio.file.FileVisitResult;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.SimpleFileVisitor;
import java.nio.file.StandardCopyOption;
import java.nio.file.attribute.BasicFileAttributes;
import java.time.Instant;
import java.util.Arrays;
import java.util.Locale;
import java.util.UUID;

/**
 * Cross-device regression test for the real desktop-generated sync fixture.
 *
 * <p>This test is instrumentation-only. It uses a {@link ContextWrapper} whose
 * {@code getFilesDir()} points at a random child of the target cache, so the
 * production store and owner binding under the real files directory are never
 * opened for writing. No account, token, network, or real Supabase service is used.
 *
 * <p>The fixture was generated by the desktop NativeStore addImport/acceptQuestions
 * path and validated there. The test asks the real Android NativeStore to accept,
 * apply, re-open, export, and reject conflicting/unsafe variants of that same JSON.
 * It also writes a receipt under the target files directory for Codex to inspect
 * after an emulator run. This source does not claim the emulator run has happened.
 */
@RunWith(AndroidJUnit4.class)
public final class CrossDeviceSyncRegressionTest {
    private static final String FIXTURE_ASSET = "desktop-sync-fixture.json";
    private static final String RECEIPT_NAME = "cross-device-sync-regression-result.json";
    private static final String TEMP_PREFIX = "cross-device-sync-";
    private static final long MIN_LARGE_ID = 1_000_000_000_000L;
    private static final long MAX_LARGE_ID_EXCLUSIVE = 1L << 52;

    private final JSONArray checks = new JSONArray();
    private final JSONObject receipt = new JSONObject();
    private boolean failedCheck;
    private boolean passed;

    private long fixtureImportId = -1L;
    private long fixtureSourceId = -1L;
    private long fixtureQuestionId = -1L;
    private String fixturePageText = "";
    private String fixtureQuestionText = "";
    private String fixtureAnswerText = "";
    private String fixtureSourceQuote = "";
    private String fixtureType = "";

    @Test
    public void desktopFixtureAppliesAndKeepsIsolatedState() throws Exception {
        Context targetContext = InstrumentationRegistry.getInstrumentation().getTargetContext();
        File cacheDir = targetContext.getCacheDir();
        assertNotNull("target cache dir", cacheDir);

        File actualStore = new File(targetContext.getFilesDir(), "native/native-store.json");
        File actualBinding = new File(targetContext.getFilesDir(), "native/sync-owner.json");
        byte[] actualStoreBefore = readIfExists(actualStore);
        byte[] actualBindingBefore = readIfExists(actualBinding);

        File root = new File(cacheDir, TEMP_PREFIX + UUID.randomUUID());
        if (!root.mkdirs()) {
            fail("Could not create isolated test directory: " + root.getName());
        }
        final File isolatedFiles = root;
        Context isolated = new ContextWrapper(targetContext) {
            @Override
            public File getFilesDir() {
                return isolatedFiles;
            }
        };

        try {
            JSONObject fixture = readFixture();
            JSONObject cleanBundle = new NativeStore(isolated).validateSyncBundle(fixture);
            record("fixtureAcceptedByAndroidNativeStore", true);

            JSONObject rawNative = fixture.getJSONObject("native");
            JSONObject rawCustom = rawNative.getJSONObject("customContent");
            JSONArray rawImports = rawNative.getJSONArray("imports");
            JSONArray rawQuestions = rawCustom.getJSONArray("customQuestions");
            JSONArray rawSources = rawCustom.getJSONArray("customSources");
            JSONArray rawAnswers = rawCustom.getJSONArray("customAnswers");

            fixtureImportId = rawImports.getJSONObject(0).getLong("id");
            fixtureSourceId = rawSources.getJSONObject(0).getLong("id");
            fixtureQuestionId = rawQuestions.getJSONObject(0).getLong("id");
            fixturePageText = rawImports.getJSONObject(0).getJSONArray("pages")
                .getJSONObject(0).getString("text");
            fixtureQuestionText = rawQuestions.getJSONObject(0).getString("question");
            fixtureAnswerText = rawAnswers.getJSONObject(0).getString("answer");
            fixtureSourceQuote = rawAnswers.getJSONObject(0).getString("sourceQuote");
            fixtureType = rawAnswers.getJSONObject(0).getString("type");

            check("hugeImportIdPreserved",
                fixtureImportId >= MIN_LARGE_ID && fixtureImportId < MAX_LARGE_ID_EXCLUSIVE);
            check("hugeSourceIdPreserved",
                fixtureSourceId >= MIN_LARGE_ID && fixtureSourceId < MAX_LARGE_ID_EXCLUSIVE);
            check("hugeQuestionIdPreserved",
                fixtureQuestionId >= MIN_LARGE_ID &&
                    fixtureQuestionId < MAX_LARGE_ID_EXCLUSIVE);

            JSONObject cleanedNative = cleanBundle.getJSONObject("native");
            JSONObject cleanedCustom = cleanedNative.getJSONObject("customContent");
            JSONArray cleanedImports = cleanedNative.getJSONArray("imports");
            JSONArray cleanedQuestions = cleanedCustom.getJSONArray("customQuestions");
            JSONArray cleanedSources = cleanedCustom.getJSONArray("customSources");
            JSONArray cleanedAnswers = cleanedCustom.getJSONArray("customAnswers");

            check("cleanImportIdMatchesFixture",
                cleanedImports.getJSONObject(0).getLong("id") == fixtureImportId);
            check("cleanSourceIdMatchesFixture",
                cleanedSources.getJSONObject(0).getLong("id") == fixtureSourceId);
            check("cleanQuestionIdMatchesFixture",
                cleanedQuestions.getJSONObject(0).getLong("id") == fixtureQuestionId);
            check("exactPageText", fixturePageText.equals(
                cleanedImports.getJSONObject(0).getJSONArray("pages")
                    .getJSONObject(0).getString("text")));
            check("exactQuestionText", fixtureQuestionText.equals(
                cleanedQuestions.getJSONObject(0).getString("question")));
            check("exactGeneratedAnswer", fixtureAnswerText.equals(
                cleanedAnswers.getJSONObject(0).getString("answer")));
            check("exactSourceQuote", fixtureSourceQuote.equals(
                cleanedAnswers.getJSONObject(0).getString("sourceQuote")));
            check("exactGeneratedType", fixtureType.equals(
                cleanedAnswers.getJSONObject(0).getString("type")));
            check("customTypeStable", fixtureType.equals(
                cleanedCustom.getJSONObject("customTypes")
                    .getString(String.valueOf(fixtureQuestionId))));

            NativeStore store = new NativeStore(isolated);
            boolean firstApply = store.applySyncNative(cleanedNative);
            check("firstApplyReportsChanged", firstApply);

            NativeStore reopened = new NativeStore(isolated);
            JSONObject bootstrap = new JSONObject(reopened.bootstrapJson());
            JSONArray bootQuestions = bootstrap.getJSONArray("customQuestions");
            JSONArray bootSources = bootstrap.getJSONArray("customSources");
            JSONArray bootAnswers = bootstrap.getJSONArray("customAnswers");
            check("reopenedQuestionId", bootQuestions.getJSONObject(0).getLong("id") ==
                fixtureQuestionId);
            check("reopenedSourceId", bootSources.getJSONObject(0).getLong("id") ==
                fixtureSourceId);
            check("reopenedAnswerQuestionId",
                bootAnswers.getJSONObject(0).getLong("question_id") == fixtureQuestionId);
            check("reopenedAnswerText", fixtureAnswerText.equals(
                bootAnswers.getJSONObject(0).getString("answer")));
            check("reopenedSourceQuote", fixtureSourceQuote.equals(
                bootAnswers.getJSONObject(0).getString("sourceQuote")));
            check("reopenedAnswerType", fixtureType.equals(
                bootAnswers.getJSONObject(0).getString("type")));

            JSONObject exportedAfterApply = reopened.exportSyncNative();
            JSONArray exportedImports = exportedAfterApply.getJSONArray("imports");
            check("exportedImportId", exportedImports.getJSONObject(0).getLong("id") ==
                fixtureImportId);
            check("exportedPageText", fixturePageText.equals(
                exportedImports.getJSONObject(0).getJSONArray("pages")
                    .getJSONObject(0).getString("text")));

            File isolatedStoreFile = new File(root, "native/native-store.json");
            byte[] beforeSecondApply = readIfExists(isolatedStoreFile);
            boolean secondApply = reopened.applySyncNative(cleanedNative);
            byte[] afterSecondApply = readIfExists(isolatedStoreFile);
            check("secondApplyIsIdempotent", !secondApply);
            check("secondApplyLeavesBytesUnchanged",
                Arrays.equals(beforeSecondApply, afterSecondApply));

            JSONObject collision = new JSONObject(cleanedNative.toString());
            collision.getJSONObject("customContent").getJSONArray("customQuestions")
                .getJSONObject(0).put("question", "同一编号但内容冲突的题干。");
            byte[] beforeCollision = readIfExists(isolatedStoreFile);
            expectUserException("questionIdTextCollisionRejected",
                () -> reopened.applySyncNative(collision));
            check("collisionLeavesBytesUnchanged",
                Arrays.equals(beforeCollision, readIfExists(isolatedStoreFile)));
            String preservedQuestion = reopened.exportSyncNative()
                .getJSONObject("customContent").getJSONArray("customQuestions")
                .getJSONObject(0).getString("question");
            check("collisionPreservedOriginal", fixtureQuestionText.equals(preservedQuestion));

            JSONObject sensitive = new JSONObject(cleanedNative.toString());
            sensitive.getJSONObject("customContent").getJSONArray("customQuestions")
                .getJSONObject(0).getJSONObject("metadata").put("token", "not-a-real-secret");
            byte[] beforeSensitive = readIfExists(isolatedStoreFile);
            expectUserException("nestedSensitiveKeyRejected",
                () -> reopened.applySyncNative(sensitive));
            check("sensitiveLeavesBytesUnchanged",
                Arrays.equals(beforeSensitive, readIfExists(isolatedStoreFile)));

            for (String field : new String[]{"userToken", "providerApiKey", "clientSecret"}) {
                JSONObject unsafe = new JSONObject(cleanedNative.toString());
                unsafe.getJSONObject("customContent").getJSONArray("customQuestions")
                    .getJSONObject(0).getJSONObject("metadata").put(field, "synthetic-only");
                expectUserException("sensitiveSuffixRejected_" + field,
                    () -> reopened.applySyncNative(unsafe));
            }

            JSONObject edited = new JSONObject(cleanedNative.toString());
            String editedText = "用户修订：" + fixtureAnswerText;
            edited.getJSONObject("customContent").getJSONArray("customAnswers")
                .getJSONObject(0).put("answer", editedText).put("userEdited", true);
            reopened.applySyncNative(edited);
            JSONObject generated = new JSONObject(cleanedNative.toString());
            generated.getJSONObject("customContent").getJSONArray("customAnswers")
                .getJSONObject(0).put("answer", "龘自动生成答案").put("userEdited", false);
            reopened.applySyncNative(generated);
            check("editedAnswerWinsAcrossRepeatedApplies", editedText.equals(
                reopened.exportSyncNative().getJSONObject("customContent")
                    .getJSONArray("customAnswers").getJSONObject(0).getString("answer")));
            check("answerMergeConverges", !reopened.applySyncNative(generated));

            JSONObject conflictingType = new JSONObject(cleanedNative.toString());
            String chosenType = fixtureType.compareTo("论述题") >= 0 ? fixtureType : "论述题";
            conflictingType.getJSONObject("customContent").getJSONObject("customTypes")
                .put(String.valueOf(fixtureQuestionId), "论述题");
            reopened.applySyncNative(conflictingType);
            check("typeConflictAcceptedAndConverges", chosenType.equals(
                reopened.exportSyncNative().getJSONObject("customContent")
                    .getJSONObject("customTypes").getString(String.valueOf(fixtureQuestionId))));

            String ownerA = UUID.randomUUID().toString();
            String ownerB = UUID.randomUUID().toString();
            reopened.requireSyncOwner(ownerA.toUpperCase(Locale.ROOT));
            check("ownerBindingNormalized", ownerA.equals(reopened.getSyncBoundOwnerId()));
            expectUserException("otherOwnerRefused",
                () -> reopened.requireSyncOwner(ownerB));
            check("originalOwnerRetained", ownerA.equals(reopened.getSyncBoundOwnerId()));

            JSONObject fakeApiConfig = new JSONObject();
            fakeApiConfig.put("serviceName", "fixture-local");
            fakeApiConfig.put("baseUrl", "https://example.invalid/v1");
            fakeApiConfig.put("model", "fixture-model");
            fakeApiConfig.put("maxQuestions", 5);
            reopened.saveApiConfig(fakeApiConfig);
            reopened.saveReminder(false, "20:30");
            reopened.saveUpdateManifestUrl("https://example.invalid/update.json");

            JSONObject exportWithConfig = reopened.exportSyncNative();
            check("exportExcludesApiConfig", !exportWithConfig.has("apiConfig"));
            check("exportExcludesReminder", !exportWithConfig.has("reminder"));
            check("exportExcludesUpdateConfig", !exportWithConfig.has("updateConfig"));
            check("localApiConfigRetained", "fixture-local".equals(
                reopened.getApiConfig().optString("serviceName")));
            check("localReminderRetained", "20:30".equals(
                reopened.getReminder().optString("time")));
            check("localUpdateConfigRetained", reopened.getUpdateManifestUrl()
                .startsWith("https://example.invalid/"));

            check("actualAppStoreUnchanged",
                Arrays.equals(actualStoreBefore, readIfExists(actualStore)));
            check("actualOwnerBindingUnchanged",
                Arrays.equals(actualBindingBefore, readIfExists(actualBinding)));
            passed = true;
        } catch (AssertionError failure) {
            recordFailure(failure);
            throw failure;
        } catch (Exception failure) {
            recordFailure(failure);
            throw failure;
        } finally {
            try {
                boolean actualStoreUnchanged = false;
                boolean actualBindingUnchanged = false;
                try {
                    actualStoreUnchanged = Arrays.equals(actualStoreBefore,
                        readIfExists(actualStore));
                    actualBindingUnchanged = Arrays.equals(actualBindingBefore,
                        readIfExists(actualBinding));
                } catch (IOException exception) {
                    receipt.put("actualDataCheckError", exception.getClass().getSimpleName());
                }
                receipt.put("actualAppStoreUnchanged", actualStoreUnchanged);
                receipt.put("actualOwnerBindingUnchanged", actualBindingUnchanged);
                receipt.put("passed", passed && !failedCheck && actualStoreUnchanged &&
                    actualBindingUnchanged);
                writeReceipt(targetContext, receipt);
            } finally {
                removeExactTestRoot(root, cacheDir);
            }
        }
    }

    private void recordFailure(Throwable failure) {
        record("failure", false, failure.getClass().getSimpleName());
    }

    private void check(String name, boolean ok) {
        record(name, ok, "");
        assertTrue(name, ok);
    }

    private void expectUserException(String name, CheckedAction action) throws Exception {
        boolean rejected = false;
        String message = "";
        try {
            action.run();
        } catch (UserException exception) {
            rejected = true;
            message = exception.getMessage() == null ? "" : exception.getMessage();
        }
        record(name, rejected, rejected ? message : "no UserException");
        assertTrue(name, rejected);
    }

    private void record(String name, boolean ok) {
        record(name, ok, "");
    }

    private void record(String name, boolean ok, String detail) {
        if (!ok) {
            failedCheck = true;
        }
        try {
            JSONObject item = new JSONObject();
            item.put("name", name);
            item.put("ok", ok);
            if (detail != null && !detail.isEmpty()) {
                item.put("detail", detail);
            }
            checks.put(item);
        } catch (JSONException exception) {
            throw new IllegalStateException(exception);
        }
    }

    private JSONObject readFixture() throws Exception {
        try (InputStream input = InstrumentationRegistry.getInstrumentation()
            .getContext().getAssets().open(FIXTURE_ASSET)) {
            ByteArrayOutputStream output = new ByteArrayOutputStream();
            byte[] buffer = new byte[8192];
            int read;
            while ((read = input.read(buffer)) >= 0) {
                if (read > 0) {
                    output.write(buffer, 0, read);
                }
            }
            return new JSONObject(output.toString(StandardCharsets.UTF_8.name()));
        }
    }

    private void writeReceipt(Context targetContext, JSONObject value) throws IOException {
        try {
            value.put("test", "CrossDeviceSyncRegressionTest");
            value.put("fixtureAsset", FIXTURE_ASSET);
            value.put("fixtureImportId", fixtureImportId);
            value.put("fixtureSourceId", fixtureSourceId);
            value.put("fixtureQuestionId", fixtureQuestionId);
            value.put("fixturePageText", fixturePageText);
            value.put("fixtureQuestionText", fixtureQuestionText);
            value.put("fixtureAnswerText", fixtureAnswerText);
            value.put("fixtureSourceQuote", fixtureSourceQuote);
            value.put("fixtureType", fixtureType);
            value.put("networkUsed", false);
            value.put("accountsUsed", false);
            value.put("generatedAt", Instant.now().toString());
            value.put("checks", checks);
        } catch (JSONException exception) {
            throw new IOException("Could not assemble receipt", exception);
        }

        File target = new File(targetContext.getFilesDir(), RECEIPT_NAME);
        File temporary = new File(targetContext.getFilesDir(), RECEIPT_NAME + ".tmp");
        byte[] encoded;
        try {
            encoded = value.toString(2).getBytes(StandardCharsets.UTF_8);
        } catch (JSONException exception) {
            throw new IOException("Could not encode receipt", exception);
        }
        try (FileOutputStream output = new FileOutputStream(temporary)) {
            output.write(encoded);
            output.getFD().sync();
        }
        try {
            Files.move(temporary.toPath(), target.toPath(),
                StandardCopyOption.REPLACE_EXISTING,
                StandardCopyOption.ATOMIC_MOVE);
        } catch (AtomicMoveNotSupportedException exception) {
            Files.move(temporary.toPath(), target.toPath(),
                StandardCopyOption.REPLACE_EXISTING);
        }
    }

    /**
     * Removes only the exact random child we created. The canonical parent must be
     * the target cache and the name must retain the test prefix. Symlinks are never
     * followed: a link is deleted as a link, never as its target.
     */
    private static void removeExactTestRoot(File root, File cacheDir) throws IOException {
        if (root == null || !root.exists()) {
            return;
        }
        File canonicalRoot = root.getCanonicalFile();
        File canonicalCache = cacheDir.getCanonicalFile();
        if (!canonicalCache.equals(canonicalRoot.getParentFile())) {
            throw new IOException("Refusing to remove a non-child test directory");
        }
        if (!canonicalRoot.getName().startsWith(TEMP_PREFIX)) {
            throw new IOException("Refusing to remove an unrecognized test directory");
        }
        if (Files.isSymbolicLink(canonicalRoot.toPath())) {
            throw new IOException("Refusing to remove a symlinked test directory");
        }
        Files.walkFileTree(canonicalRoot.toPath(), new SimpleFileVisitor<Path>() {
            @Override
            public FileVisitResult visitFile(Path file, BasicFileAttributes attributes)
                throws IOException {
                // walkFileTree without FOLLOW_LINKS treats a symlink as a file here.
                Files.delete(file);
                return FileVisitResult.CONTINUE;
            }

            @Override
            public FileVisitResult postVisitDirectory(Path directory, IOException failure)
                throws IOException {
                if (failure != null) {
                    throw failure;
                }
                Files.delete(directory);
                return FileVisitResult.CONTINUE;
            }
        });
    }

    private static byte[] readIfExists(File file) throws IOException {
        if (file == null || !file.isFile()) {
            return null;
        }
        if (file.length() > 64L * 1024 * 1024) {
            throw new IOException("Unexpectedly large file");
        }
        try (FileInputStream input = new FileInputStream(file)) {
            ByteArrayOutputStream output = new ByteArrayOutputStream();
            byte[] buffer = new byte[8192];
            int read;
            while ((read = input.read(buffer)) >= 0) {
                if (read > 0) {
                    output.write(buffer, 0, read);
                }
            }
            return output.toByteArray();
        }
    }

    private interface CheckedAction {
        void run() throws Exception;
    }
}
